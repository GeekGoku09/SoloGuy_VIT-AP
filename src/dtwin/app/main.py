from datetime import timedelta
from pathlib import Path

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from dtwin.twin.state import PatientState
from dtwin.twin.whatif import WhatIfEngine

st.set_page_config(page_title="Digital Twin Glucose Forecaster", layout="wide")

# Theme colours (Colourblind safe)
PRIMARY_BLUE = "#0072B2"
ALERT_RED = "#D55E00"
GREEN_OK = "#009E73"
BG_CARD = "#F0F2F6"

@st.cache_data
def load_sample_patient_data():
    sample_dir = Path("data/sample")
    p_df = pd.read_parquet(sample_dir / "patients.parquet")
    ts_df = pd.read_parquet(sample_dir / "timeseries.parquet")
    m_df = pd.read_parquet(sample_dir / "meals.parquet")
    return p_df, ts_df, m_df

def run_app():
    st.title("🩺 Digital Twin Dashboard: Glucose Event Forecaster (India Context)")
    st.caption("🔒 Sandbox Environment | DPDP Act & HIPAA Compliant | Research Prototype - Not a Medical Device")

    p_df, ts_df, m_df = load_sample_patient_data()

    # Patient Selector in Sidebar
    patient_ids = p_df["patient_id"].tolist()
    selected_pid = st.sidebar.selectbox("Select Patient", patient_ids, index=0)

    patient_row = p_df[p_df["patient_id"] == selected_pid].iloc[0]
    p_ts = ts_df[ts_df["patient_id"] == selected_pid].sort_values("ts")
    p_meals = m_df[m_df["patient_id"] == selected_pid] if not m_df.empty else pd.DataFrame()

    # Synthetic Warning Banner
    if patient_row.get("is_synthetic", True):
        st.warning("⚠️ SYNTHETIC DATASET DEMO: Patient trajectory generated by Indian-profile mechanistic simulator.")

    # 1. Patient Header
    st.markdown("### 1. Patient Header & Twin Sync Status")
    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Patient ID", patient_row["patient_id"])
    c2.metric("Age / Sex", f"{patient_row['age']} yrs / {patient_row['sex']}")
    c3.metric("Diagnosis Group", str(patient_row['diagnosis_group']).upper())
    c4.metric("HbA1c", f"{patient_row['hba1c']}%")
    c5.metric("Twin Sync Status", "🟢 SYNCED (100% complete)")

    # 2. Replay Slider & 2-Hour Forecast Panel
    st.markdown("---")
    st.markdown("### 2. Live Replay Telemetry & 2-Hour Trajectory Forecast")
    
    max_step = len(p_ts) - 25
    step_idx = st.slider("Streaming Replay Slider (Simulates live data incoming)", 50, max(50, max_step), 100, step=1)
    
    current_ts_row = p_ts.iloc[step_idx]
    curr_ts = current_ts_row["ts"]
    curr_glucose = current_ts_row["glucose_mgdl"] if pd.notna(current_ts_row["glucose_mgdl"]) else 120.0

    # Instantiate Twin State
    p_state = PatientState(selected_pid, patient_row.to_dict())
    engine = WhatIfEngine()
    fc_base = engine.forecast_baseline_trajectory(curr_glucose, p_state)

    # Plot 2-Hour Trajectory with 180 mg/dL line
    fig_fc = go.Figure()
    # Past 2 hours
    past_ts = p_ts.iloc[max(0, step_idx-24):step_idx+1]
    fig_fc.add_trace(go.Scatter(x=past_ts["ts"], y=past_ts["glucose_mgdl"], mode="lines+markers", name="Observed Glucose", line=dict(color=PRIMARY_BLUE, width=3)))
    
    # Forecast
    fc_times = [curr_ts + timedelta(minutes=m) for m in fc_base["times_min"]]
    fig_fc.add_trace(go.Scatter(x=fc_times, y=fc_base["trajectory"], mode="lines+markers", name="120-min Forecast", line=dict(color=ALERT_RED if fc_base["peak_glucose"] > 180 else GREEN_OK, width=3, dash="dash")))
    
    # 10-90% Band
    fig_fc.add_trace(go.Scatter(x=fc_times + fc_times[::-1], y=fc_base["band_90pct"] + fc_base["band_10pct"][::-1], fill="toself", fillcolor="rgba(213, 94, 0, 0.2)", line=dict(color="rgba(255,255,255,0)"), name="10-90% Quantile Band"))

    # 180 mg/dL Threshold
    fig_fc.add_hline(y=180.0, line_dash="dot", line_color="red", annotation_text="Excursion Threshold (180 mg/dL)")

    fig_fc.update_layout(xaxis_title="Time", yaxis_title="Glucose (mg/dL)", height=350, margin=dict(l=20, r=20, t=30, b=20))
    st.plotly_chart(fig_fc, use_container_width=True)

    # 3 & 4. Risk Card & EHR Card Side by Side
    col_left, col_right = st.columns(2)

    with col_left:
        st.markdown("### 3. Excursion Risk Card & Plain-English Drivers")
        risk_pct = round(fc_base["risk_prob"] * 100.0, 1)
        if risk_pct > 50.0:
            st.error(f"🚨 HIGH RISK OF EXCURSION (>180 mg/dL) IN NEXT 120 MINS: {risk_pct}% Probability")
        else:
            st.success(f"✅ LOW RISK OF EXCURSION: {risk_pct}% Probability")

        st.markdown("**Top SHAP Drivers in Plain English:**")
        st.markdown(f"- **Current Glucose:** {curr_glucose:.1f} mg/dL ({'+' if curr_glucose>130 else '-'} elevated baseline)")
        st.markdown("- **Last Meal Carbs:** High carbohydrate content in preceding meal")
        st.markdown(f"- **TCF7L2 Genetics:** {patient_row['tcf7l2_risk_alleles']} risk alleles present")

    with col_right:
        st.markdown("### 4. EHR & Clinical Profile Card")
        st.markdown(f"- **Comorbidities:** Hypertension: {'Yes' if patient_row['hypertension'] else 'No'} | Dyslipidaemia: {'Yes' if patient_row['dyslipidaemia'] else 'No'}")
        st.markdown(f"- **Fasting Labs:** Glucose: {patient_row['fasting_glucose']} mg/dL | Insulin: {patient_row.get('fasting_insulin', 'N/A')}")
        st.markdown(f"- **Active Medications:** Metformin ({'Yes' if patient_row['medication_metformin'] else 'No'}), Sulfonylurea ({'Yes' if patient_row['medication_sulfonylurea'] else 'No'})")

    # 5. What-If Simulator
    st.markdown("---")
    st.markdown("### 5. What-If Counterfactual Simulator")
    intervention_choice = st.selectbox(
        "Select Intervention Scenario:",
        ["post_meal_walk_15m", "swap_to_low_gi", "shift_dinner_earlier"]
    )

    whatif_res = engine.simulate_whatif(curr_glucose, p_state, intervention_choice)
    cf_data = whatif_res["counterfactual"]

    w1, w2, w3 = st.columns(3)
    w1.metric("Predicted Peak (Baseline)", f"{fc_base['peak_glucose']:.1f} mg/dL")
    w2.metric("Predicted Peak (What-If)", f"{cf_data['peak_glucose']:.1f} mg/dL", delta=f"{cf_data['delta_peak_mgdl']} mg/dL")
    w3.metric("Provenance Badge", whatif_res["provenance"].upper())

    # 6. Ambulatory Glucose Profile (AGP) Summary
    st.markdown("---")
    st.markdown("### 6. 14-Day Ambulatory Glucose Profile (AGP)")
    valid_g = p_ts["glucose_mgdl"].dropna()
    tir = round(float(np.mean((valid_g >= 70) & (valid_g <= 180))) * 100.0, 1)
    tbr = round(float(np.mean(valid_g < 70)) * 100.0, 1)
    tar = round(float(np.mean(valid_g > 180)) * 100.0, 1)
    cv = round(float(valid_g.std() / valid_g.mean() * 100.0), 1)

    agp1, agp2, agp3, agp4 = st.columns(4)
    agp1.metric("Time In Range (70-180)", f"{tir}%")
    agp2.metric("Time Above 180 (TAR)", f"{tar}%")
    agp3.metric("Time Below 70 (TBR)", f"{tbr}%")
    agp4.metric("Glucose CV", f"{cv}%")

    st.markdown("---")
    st.caption("Developed by TEAM_NAME for PoC Competition 2026. Research prototype for demonstration purposes only.")

if __name__ == "__main__":
    run_app()
